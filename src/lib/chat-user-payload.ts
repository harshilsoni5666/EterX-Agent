import { normalizePathForComparison } from './path-utils';

/** Keep old checkpoints readable while removing the former latest-message-only instruction. */
export function unwrapCurrentUserRequest(value: string): string | null {
  const normalized = value.replace(/\r\n/g, '\n');
  const opening = /^\[CURRENT USER REQUEST(?: - EXECUTE ONLY THIS)?\]\n/.exec(normalized);
  const endIndex = normalized.lastIndexOf('\n[END CURRENT USER REQUEST]');
  if (!opening || endIndex < opening[0].length) return null;
  return normalized.slice(opening[0].length, endIndex);
}

/** Migrate only sealed request carriers; leave quoted text and tool protocols intact. */
export function neutralizeCurrentUserRequestCarriers(contents: any[]): any[] {
  const neutralize = (text: string): string =>
    unwrapCurrentUserRequest(text) === null ? text
      : text.replace(/^\[CURRENT USER REQUEST - EXECUTE ONLY THIS\](?=\r?\n)/, '[CURRENT USER REQUEST]');
  let changed = false;
  const migrated = contents.map(message => {
    if (message?.role !== 'user') return message;
    const next = { ...message };
    let messageChanged = false;
    for (const field of ['content', 'parts', 'text']) {
      const value = message[field];
      if (typeof value === 'string') {
        const text = neutralize(value);
        if (text !== value) { next[field] = text; messageChanged = true; }
      } else if (Array.isArray(value)) {
        const blocks = value.map(part => {
          if (typeof part?.text !== 'string' || part?.thought === true) return part;
          const text = neutralize(part.text);
          if (text === part.text) return part;
          messageChanged = true;
          return { ...part, text };
        });
        if (messageChanged) next[field] = blocks;
      }
    }
    if (!messageChanged) return message;
    changed = true;
    return next;
  });
  return changed ? migrated : contents;
}

/** Unwrap only envelopes generated by our runtime, never arbitrary quoted text. */
export function visibleUserRequest(value: unknown): string {
  const text = String(value ?? '');
  const builder = text.match(/^\s*\[AGENT BUILDER REQUEST\]\s*\r?\nTarget agent ID:[^\r\n]*\r?\n\s*\r?\n\[USER REQUEST\]\s*\r?\n([\s\S]*)$/i);
  if (builder) return builder[1];
  const attachmentEnvelope = /^\s*\[USER ATTACHED FILES\]\r?\nThe following original files are attached through the selected provider's native file\/media input:/i.test(text);
  const visionEnvelope = /^\s*\[MULTIMODAL CONTEXT\] \d+ image\(s\) are attached to this message\./.test(text);
  const pastedEnvelope = /^\s*\[PASTED TEXT REFERENCES\]\r?\nThe user attached pasted text as local UTF-8 files\./.test(text);
  if (attachmentEnvelope || visionEnvelope || pastedEnvelope) {
    const request = /(?:^|\r?\n)\[USER REQUEST\]\r?\n/.exec(text);
    if (request) return text.slice(request.index + request[0].length);
  }
  return text;
}

/** Sparse receipts enrich an attachment; they cannot discard its durable path. */
export function mergeUserAttachments(previous: unknown, incoming: unknown): any[] {
  const result = Array.isArray(previous) ? previous.filter(Boolean).map(item => ({ ...item })) : [];
  for (const attachment of Array.isArray(incoming) ? incoming.filter(Boolean) : []) {
    const index = result.findIndex(item => {
      if (item.id && attachment.id && item.id === attachment.id) return true;
      const left = [item.localPath, item.path, item.originalPath].map(normalizePathForComparison).filter(Boolean);
      const right = [attachment.localPath, attachment.path, attachment.originalPath].map(normalizePathForComparison).filter(Boolean);
      return left.some(path => right.includes(path));
    });
    if (index < 0) result.push({ ...attachment });
    else {
      for (const [key, value] of Object.entries(attachment)) {
        if (value !== undefined && value !== null && value !== '') result[index][key] = value;
      }
    }
  }
  return result;
}
