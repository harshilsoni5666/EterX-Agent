  /**
   * Internal cleanup of all WebSocket, audio capture, and playback resources.
   */
  private cleanup(preserveVisualCapture = false): void {
    this.interactionStatus = null;
    this.isInterruptedThisTurn = false;
    this.localInterruptionPending = false;
    this.authController?.abort();
    this.authController = null;
    this.finishThinking();
    this.internalTextTurn = false;
    if (this.ws) {
      this.rejectConnectionReady(this.ws, new Error('Live connection ended before becoming ready.'));
    }
    if (!preserveVisualCapture) {
      this.stopCamera();
      this.stopScreenShare();
      this.pendingTextTurns = [];
      this.reconnectAttempts = 0;
      if (this.reconnectTimer) {
        clearTimeout(this.reconnectTimer);
        this.reconnectTimer = null;
      }
    }
    this.toolAbortControllers.forEach((controller, callId) => {
      controller.abort();
      const call = this.toolCallResults.get(callId);
      if (call && !call.response) {
        call.response = {
          id: callId, name: call.name,
          response: { error: 'The connection ended during this action. Read its current state before retrying; it may already have taken effect.' },
        };
      }
      this.emitActivity({
        id: `live_tool_${callId}`, kind: 'tool', phase: 'blocked',
        label: 'Live connection interrupted', toolName: call?.name,
        detail: 'Read the task status before retrying an action that may already have started.',
        startedAt: this.toolActivityStarts.get(`live_tool_${callId}`) || Date.now(),
        completedAt: Date.now(),
      });
    });
    this.toolActivityStarts.clear();
    this.toolAbortControllers.clear();
    if (!preserveVisualCapture) this.toolCallResults.clear();
    this.cancelledToolCallIds.clear();
    this.callbacks.onToolCallActive?.(null);
    this.bargeInCandidateFrames = 0;
    this.lastBargeInCandidateAt = 0;
    if (preserveVisualCapture) {
      const interruptedEvent = this.activeSystemEvent;
      this.activeSystemEvent = null;
      if (interruptedEvent) {
        this.deliveredSystemEventIds.delete(interruptedEvent.id);
        if (!this.queuedSystemEventIds.has(interruptedEvent.id)) {
          this.systemEventQueue.unshift(interruptedEvent);
          this.queuedSystemEventIds.add(interruptedEvent.id);
        }
      }
    } else {
      this.systemEventQueue = [];
      this.queuedSystemEventIds.clear();
      this.activeSystemEvent = null;
      this.activeObjective = null;
    }
    if (this.systemEventDrainTimer) {
      clearTimeout(this.systemEventDrainTimer);
      this.systemEventDrainTimer = null;
    }
    cancelAnimationFrame(this.modelVolumeLoopId);
    this.modelVolumeLoopId = 0;
    this.callbacks.onMicVolume?.(0);
    this.callbacks.onModelVolume?.(0);
    // Stop audio capture
    if (this.scriptProcessor) {
      this.scriptProcessor.disconnect();
      this.scriptProcessor = null;
    }
    if (this.sourceNode) {
      this.sourceNode.disconnect();
      this.sourceNode = null;
    }
    if (this.captureSink) {
      this.captureSink.disconnect();
      this.captureSink = null;
    }
    if (this.captureContext) {
      this.captureContext.close().catch(() => { });
      this.captureContext = null;
    }
    if (this.mediaStream) {
      this.mediaStream.getTracks().forEach(t => t.stop());
      this.mediaStream = null;
    }

    // Stop playback without finalizing a half-finished turn during teardown.
    this.pendingTurnCompletion = null;
    this.flushPlayback();
    if (this.playbackContext) {
      this.playbackContext.close().catch(() => { });
      this.playbackContext = null;
    }
    this.playbackAnalyser = null;
    this.playbackGain = null;
    this.nextPlayTime = 0;

    // Close WebSocket
    if (this.ws) {
      if (this.ws.readyState === WebSocket.OPEN || this.ws.readyState === WebSocket.CONNECTING) {
        this.ws.close();
      }
      this.ws = null;
    }
  }

