export type GitView = 'changes' | 'branches' | 'history' | 'stashes';
export type GitFileStats = { added: number; removed: number; binary: boolean };
export type GitFile = {
  path: string;
  originalPath?: string;
  index: string;
  working: string;
  untracked: boolean;
  conflicted: boolean;
  stagedStats?: GitFileStats;
  workingStats?: GitFileStats;
};
export type GitSnapshot = {
  available: true;
  root: string;
  gitDirectory: string;
  branch: string;
  head: string;
  detached: boolean;
  upstream: string;
  ahead: number;
  behind: number;
  remotes: string[];
  files: GitFile[];
  operation: string;
  revision: string;
};
export type GitUnavailable = { available: false; root: string; reason: 'not-repository' | 'not-installed' };
export type GitStatus = GitSnapshot | GitUnavailable;
export type GitBranch = { name: string; current: boolean; remote: boolean; upstream: string; subject: string; worktree: string };
export type GitCommit = { hash: string; shortHash: string; author: string; date: string; subject: string; refs: string };
export type GitStash = { ref: string; hash: string; subject: string; date: string };
export type GitDiff = { text: string; truncated: boolean; token: string; notice?: string };
export type GitAction = 'init' | 'stage' | 'unstage' | 'commit' | 'fetch' | 'pull' | 'push' | 'create-branch' | 'switch-branch' | 'delete-branch' | 'merge' | 'stash-save' | 'stash-apply' | 'stash-drop' | 'discard' | 'add-remote' | 'set-identity';
export type GitMutation = {
  action: GitAction;
  root: string;
  revision?: string;
  paths?: string[];
  message?: string;
  branch?: string;
  branchSource?: 'local' | 'remote';
  remote?: string;
  url?: string;
  method?: 'merge' | 'squash';
  includeUntracked?: boolean;
  stash?: string;
  stashHash?: string;
  token?: string;
  confirmed?: boolean;
  name?: string;
  email?: string;
};
export type GitMutationResult = { message: string };
